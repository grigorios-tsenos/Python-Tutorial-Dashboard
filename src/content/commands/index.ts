import { LESSONS } from '../index'
import usage from './usage.json'
import { BUILTIN_CARDS } from './cards/builtins'
import { NUMPY_CARDS } from './cards/numpy'
import { PANDAS_CARDS } from './cards/pandas'
import { MATPLOTLIB_CARDS } from './cards/matplotlib'
import { SKLEARN_CARDS } from './cards/sklearn'
import { PYDANTIC_CARDS } from './cards/pydantic'
import { LANGCHAIN_CARDS } from './cards/langchain'
import { LANGGRAPH_CARDS } from './cards/langgraph'
import { MLFLOW_CARDS } from './cards/mlflow'
import { SPARK_CARDS } from './cards/spark'
import { STDLIB_CARDS } from './cards/stdlib'

export interface CommandParam {
  name: string
  text: string
}

/** Reference knowledge about one command: what it is and what it takes, never how a lesson uses it. */
export interface CommandCard {
  /** usage keys this card explains (see scripts/command_usage.py) */
  keys: string[]
  /** how lessons write it, e.g. `np.isnan` or `DataFrame.groupby` */
  name: string
  kind: 'function' | 'method' | 'class' | 'attribute' | 'constant' | 'decorator' | 'exception'
  /** generic call shape with the parameters that matter, e.g. `np.isnan(x)` */
  signature: string
  /** one or two plain sentences: what it does */
  summary: string
  params: CommandParam[]
  /** what it gives back; empty for constants */
  returns: string
}

/** Python every lesson assumes: these never get a card. */
export const BASELINE = new Set(['print', 'len', 'range', 'int', 'float', 'str', 'bool', 'list', 'dict', 'set', 'tuple'].map(name => `builtins.${name}`))

export const COMMAND_CARDS: CommandCard[] = [
  ...BUILTIN_CARDS, ...STDLIB_CARDS, ...NUMPY_CARDS, ...PANDAS_CARDS, ...MATPLOTLIB_CARDS, ...SKLEARN_CARDS,
  ...PYDANTIC_CARDS, ...LANGCHAIN_CARDS, ...LANGGRAPH_CARDS, ...MLFLOW_CARDS, ...SPARK_CARDS,
]

export const CARD_BY_KEY: Record<string, CommandCard> = Object.fromEntries(COMMAND_CARDS.flatMap(card => card.keys.map(key => [key, card])))

/**
 * Library commands each lesson unit reads, in source order. A unit is a guided step for coding lessons
 * and a non-empty code line for prediction lessons. Generated by tests/commands.test.ts (`npx vitest -u tests/commands.test.ts`).
 */
export const USAGE = usage as Record<string, string[][]>

export interface UnitCommands {
  /** first met here, in learning order */
  fresh: CommandCard[]
  /** met in an earlier unit or lesson */
  known: CommandCard[]
}

let firstUse: Map<CommandCard, string> | null = null

function firstUnits(): Map<CommandCard, string> {
  if (firstUse) return firstUse
  firstUse = new Map()
  for (const lesson of LESSONS) {
    for (const [unit, keys] of (USAGE[lesson.id] ?? []).entries()) {
      for (const key of keys) {
        const card = CARD_BY_KEY[key]
        if (card && !firstUse.has(card)) firstUse.set(card, `${lesson.id}:${unit}`)
      }
    }
  }
  return firstUse
}

export function commandsFor(lessonId: string, unit: number): UnitCommands {
  const here = `${lessonId}:${unit}`
  const cards = [...new Set((USAGE[lessonId]?.[unit] ?? []).filter(key => !BASELINE.has(key)).map(key => CARD_BY_KEY[key]).filter(Boolean))]
  const first = firstUnits()
  return { fresh: cards.filter(card => first.get(card) === here), known: cards.filter(card => first.get(card) !== here) }
}
